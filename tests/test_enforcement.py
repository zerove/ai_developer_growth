"""Tests for enforcement scripts."""
import shutil
import tempfile
import unittest
from pathlib import Path

from tools.scripts.ai_quality_gate import (
    check_error_patterns,
    check_security_patterns,
    check_type_patterns,
)
from tools.scripts.check_ai_annotation import (
    has_ai_annotation,
)
from tools.scripts.validate_agent_definition import (
    validate_agent_definition,
    validate_agent_name,
)


class TestValidateAgentName(unittest.TestCase):
    """Test agent name validation."""

    def test_valid_kebab_case(self):
        """Should accept valid kebab-case names."""
        errors = validate_agent_name("code-reviewer")
        self.assertEqual(errors, [])

    def test_valid_with_numbers(self):
        """Should accept names with numbers."""
        errors = validate_agent_name("agent-v2")
        self.assertEqual(errors, [])

    def test_invalid_uppercase(self):
        """Should reject uppercase names."""
        errors = validate_agent_name("Code-Reviewer")
        self.assertGreater(len(errors), 0)

    def test_invalid_abbreviation(self):
        """Should reject abbreviations."""
        errors = validate_agent_name("code-hlp")
        self.assertGreater(len(errors), 0)

    def test_too_short(self):
        """Should reject short names."""
        errors = validate_agent_name("ab")
        self.assertGreater(len(errors), 0)


class TestValidateAgentDefinition(unittest.TestCase):
    """Test agent definition validation."""

    def setUp(self):
        self.test_dir = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.test_dir)

    def test_valid_md_format(self):
        """Should accept valid Markdown format."""
        agent_file = Path(self.test_dir) / "test-agent.md"
        agent_file.write_text("""## agent: test-agent (Test Agent)

### 指令

1. 运行 `tools/scripts/test.py` 检查代码
2. 使用 `ruff check .` 验证风格

- bash

### 约束

- 禁止删除生产数据
- 所有操作必须有日志记录
""", encoding="utf-8")

        result = validate_agent_definition(agent_file)
        self.assertTrue(result["passed"])

    def test_invalid_name(self):
        """Should reject invalid agent names."""
        agent_file = Path(self.test_dir) / "bad-name.md"
        agent_file.write_text("""## agent: BAD_NAME

### 指令

1. 运行 `tools/scripts/test.py`

### 工具

- python

### 约束

- 禁止删除生产数据
""", encoding="utf-8")

        result = validate_agent_definition(agent_file)
        self.assertFalse(result["passed"])


class TestCheckAIAnnotation(unittest.TestCase):
    """Test AI annotation checking."""

    def test_has_annotation(self):
        """Should detect AI annotation."""
        content = "# [AI-GEN] Generated by AI\nimport os"
        self.assertTrue(has_ai_annotation(content))

    def test_no_annotation(self):
        """Should detect missing annotation."""
        content = "import os\ndef test(): pass"
        self.assertFalse(has_ai_annotation(content))


class TestCheckSecurityPatterns(unittest.TestCase):
    """Test security pattern detection."""

    def test_detects_hardcoded_secret(self):
        """Should detect hardcoded secrets."""
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
            f.write('password = "secret123"')
            f.flush()
            issues = check_security_patterns(Path(f.name))
        self.assertGreater(len(issues), 0)

    def test_detects_eval(self):
        """Should detect eval usage."""
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
            f.write('result = eval(user_input)')
            f.flush()
            issues = check_security_patterns(Path(f.name))
        self.assertGreater(len(issues), 0)

    def test_clean_code(self):
        """Should pass clean code."""
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
            f.write('import os\nprint("hello")')
            f.flush()
            issues = check_security_patterns(Path(f.name))
        self.assertEqual(len(issues), 0)


