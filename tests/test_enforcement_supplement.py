class TestDetectAIGeneratedFunctions:
    """detect_ai_generated_functions 测试"""

    def test_no_functions(self):
        assert detect_ai_generated_functions("x = 1\ny = 2") == []

    def test_function_with_annotation(self):
        content = "# [AI-GEN] Generated by AI\ndef my_func(): pass"
        assert detect_ai_generated_functions(content) == []

    def test_function_without_annotation_no_indicator(self):
        content = "import os\ndef my_func(): pass"
        assert detect_ai_generated_functions(content) == []

    def test_function_with_ai_comment(self):
        content = "# AI-generated code\ndef my_func(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 1
        assert "my_func" in result[0]["function"]

    def test_function_with_generated_by_comment(self):
        content = "# Generated with Claude\ndef helper(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 1

    def test_function_with_ai_assistant_comment(self):
        content = "# AI assistant\ndef util(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 1

    def test_function_with_this_code_ai_comment(self):
        content = "# This code is AI\ndef process(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 1

    def test_function_with_this_function_generated_comment(self):
        content = "# This function was generated by GPT\ndef compute(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 1

    def test_string_with_ai_not_detected(self):
        """字符串中的 AI 关键词不应触发检测"""
        content = 'PATTERN = r"# AI assistant"\ndef my_func(): pass'
        result = detect_ai_generated_functions(content)
        # 模式定义中的 "# AI assistant
        assert len(result) == 0

    def test_multiple_functions(self):
        content = "# AI-generated\ndef a(): pass\n\ndef b(): pass"
        result = detect_ai_generated_functions(content)
        assert len(result) == 2  # 两个函数的上下文窗口都包含 AI 指标


