class TestIsInString:
    """_is_in_string 测试"""

    def test_not_in_string(self):
        assert not _is_in_string('x = eval("code")', 4)

    def test_in_double_quoted_string(self):
        assert _is_in_string('pattern = "eval()"', 11)

    def test_in_single_quoted_string(self):
        assert _is_in_string("pattern = 'eval()'", 11)

    def test_in_raw_string(self):
        assert _is_in_string('r"eval\\s*\\("', 4)

    def test_after_string(self):
        assert not _is_in_string('"hello" + eval(x)', 14)

    def test_empty_line(self):
        assert not _is_in_string("", 0)

    def test_multiple_strings(self):
        line = '"first" + "second"'
        # pos 15 在 "second" 内部
        assert _is_in_string(line, 15)
        # pos 1 在 "first" 内部
        assert _is_in_string(line, 1)
        # pos 8 不在字符串内
        assert not _is_in_string(line, 8)


class TestCheckSecurityPatterns:
    """check_security_patterns 测试"""

    def test_hardcoded_secret(self, tmp_path):
        f = tmp_path / "test.py"
        f.write_text('password = "secret123"\n')
        issues = check_security_patterns(f)
        assert len(issues) >= 1
        assert "硬编码密钥" in issues[0]["message"]

    def test_eval_not_in_string(self, tmp_path):
        f = tmp_path / "test.py"
        f.write_text("result = eval(user_input)\n")
        issues = check_security_patterns(f)
        assert len(issues) >= 1
        assert "eval()" in issues[0]["message"]

    def test_exec_not_in_string(self, tmp_path):
        f = tmp_path / "test.py"
        f.write_text("exec(code)\n")
        issues = check_security_patterns(f)
        assert len(issues) >= 1
        assert "exec()" in issues[0]["message"]

    def test_eval_in_string_no_issue(self, tmp_path):
        """eval() 在字符串定义中不应触发"""
        f = tmp_path / "test.py"
