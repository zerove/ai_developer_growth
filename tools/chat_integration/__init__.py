class DingTalkNotifier(BaseNotifier):
    """Send governance reports to DingTalk."""

    def send_report(
        self,
        issues: list[Issue],
        language: str,
        project: str = ".",
        title: str = "ADG Governance Report",
    ) -> bool:
        error_count = sum(1 for i in issues if i.severity == "error")
        warn_count = sum(1 for i in issues if i.severity == "warning")

        status = "🔴 FAIL" if error_count > 0 else ("🟡 WARN" if warn_count > 0 else "✅ PASS")
        top_issues = sorted(issues, key=lambda i: {"error": 0, "warning": 1, "info": 2}.get(i.severity, 3))[:5]

        text = f"### {title}\n\n"
        text += f"**项目:** {project} | **语言:** {language} | **状态:** {status}\n\n"
        text += f"错误: {error_count} | 警告: {warn_count} | 总计: {len(issues)}\n\n"

        if top_issues:
            text += "**主要问题:**\n"
            for i in top_issues:
                text += f"- `{i.rule_id}` {Path(i.file).name}:{i.line} {i.message}\n"

        payload = {
            "msgtype": "markdown",
            "markdown": {
                "title": f"ADG: {project}",
                "text": text,
            }
        }

        return self._post(payload)

    def send_alert(self, message: str, level: str = "warning") -> bool:
        payload = {
            "msgtype": "markdown",
            "markdown": {
                "title": "ADG Alert",
                "text": f"### ⚠️ ADG Alert ({level})\n\n{message}",
            }
        }
        return self._post(payload)


# ─────────────────────────────────────────────────────────────
# Factory
# ─────────────────────────────────────────────────────────────

def create_notifier(webhook_url: str) -> BaseNotifier:
    """Create appropriate notifier based on webhook URL."""
    if "slack.com" in webhook_url or webhook_url.startswith("slack://"):
        url = webhook_url.replace("slack://", "https://hooks.slack.com/services/")
        return SlackNotifier(url)
    elif "feishu" in webhook_url or "larksuite" in webhook_url:
        return FeishuNotifier(webhook_url)
    elif "dingtalk" in webhook_url or "oapi.dingtalk" in webhook_url:
        return DingTalkNotifier(webhook_url)
    else:
        # Default to Slack format
        return SlackNotifier(webhook_url)
