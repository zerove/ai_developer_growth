from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any
from urllib.request import urlopen, Request
from urllib.error import URLError

from tools.scripts.adg_cli import Issue


# ─────────────────────────────────────────────────────────────
# Base Notifier
# ─────────────────────────────────────────────────────────────

class BaseNotifier:
    """Base class for chat notifications."""

    def __init__(self, webhook_url: str):
        self.webhook_url = webhook_url

    def _post(self, payload: dict) -> bool:
        """Post payload to webhook."""
        try:
            data = json.dumps(payload).encode("utf-8")
            req = Request(self.webhook_url, data=data, headers={"Content-Type": "application/json"})
            with urlopen(req, timeout=10) as resp:
                return resp.status == 200
        except Exception:
            return False

    def send_report(
        self,
        issues: list[Issue],
        language: str,
        project: str = ".",
        title: str = "ADG Governance Report",
    ) -> bool:
        raise NotImplementedError

    def send_alert(
        self,
        message: str,
        level: str = "warning",
    ) -> bool:
        raise NotImplementedError


# ─────────────────────────────────────────────────────────────
# Slack
# ─────────────────────────────────────────────────────────────

class SlackNotifier(BaseNotifier):
    """Send governance reports to Slack."""

    def send_report(
        self,
        issues: list[Issue],
        language: str,
        project: str = ".",
        title: str = "ADG Governance Report",
    ) -> bool:
        error_count = sum(1 for i in issues if i.severity == "error")
        warn_count = sum(1 for i in issues if i.severity == "warning")
        info_count = sum(1 for i in issues if i.severity == "info")

        # Determine emoji
        if error_count > 0:
            status_emoji = "🔴"
        elif warn_count > 0:
            status_emoji = "🟡"
        else:
            status_emoji = "🟢"

        # Build blocks
        blocks = [
            {
                "type": "header",
                "text": {"type": "plain_text", "text": f"{status_emoji} {title}"}
            },
            {
                "type": "section",
                "fields": [
                    {"type": "mrkdwn", "text": f"*Project:*\n{project}"},
                    {"type": "mrkdwn", "text": f"*Language:*\n{language}"},
                    {"type": "mrkdwn", "text": f"*Errors:*\n{error_count}"},
                    {"type": "mrkdwn", "text": f"*Warnings:*\n{warn_count}"},
                    {"type": "mrkdwn", "text": f"*Info:*\n{info_count}"},
                    {"type": "mrkdwn", "text": f"*Total:*\n{len(issues)}"},
                ]
            },
        ]

        # Add top issues
        top_issues = sorted(issues, key=lambda i: {"error": 0, "warning": 1, "info": 2}.get(i.severity, 3))[:5]
        if top_issues:
            issue_text = "\n".join([
                f"• `{i.rule_id}` {i.file}:{i.line} - {i.message}"
                for i in top_issues
            ])
            blocks.append({
                "type": "section",
                "text": {"type": "mrkdwn", "text": f"*Top Issues:*\n{issue_text}"}
            })

        blocks.append({"type": "divider"})
        blocks.append({
            "type": "context",
            "elements": [{"type": "mrkdwn", "text": f"Generated by ADG Governance | {datetime.now().strftime('%Y-%m-%d %H:%M')}"}]
        })

        payload = {"blocks": blocks}
        return self._post(payload)

    def send_alert(self, message: str, level: str = "warning") -> bool:
        emoji = {"error": "🔴", "warning": "🟡", "info": "🔵"}.get(level, "⚠️")
        payload = {
            "blocks": [
                {
                    "type": "section",
                    "text": {"type": "mrkdwn", "text": f"{emoji} *ADG Alert*\n{message}"}
                }
            ]
        }
        return self._post(payload)


