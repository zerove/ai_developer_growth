#!/usr/bin/env python3
"""
AI 代码标注检查器

检查代码中是否包含 AI 生成标注，确保 AI 编写的代码可追溯。
符合 GOVERNANCE.md 关于 AI 代码标注的要求。

用法:
    python tools/scripts/check_ai_annotation.py [--strict] [--path PATH]

标注格式:
    # ai-generated: <model> <date> <purpose>
    # ai-assisted: <model> <date> <purpose>
    # ai-reviewed: <model> <date>
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

AI_GENERATED_PATTERN = re.compile(r"#\s*ai-generated:\s*(\S+)\s+(\S+)\s+(.+)")
AI_ASSISTED_PATTERN = re.compile(r"#\s*ai-assisted:\s*(\S+)\s+(\S+)\s+(.+)")
AI_REVIEWED_PATTERN = re.compile(r"#\s*ai-reviewed:\s*(\S+)\s+(\S+)")
AI_GEN_PATTERN = re.compile(r"#\s*\[AI-GEN\]")

# 需要检查的文件类型
TARGET_EXTENSIONS = {".py", ".js", ".ts", ".jsx", ".tsx", ".rs", ".go", ".java", ".kt"}

# AI 生成注释标识 (detect_ai_generated_functions 使用)
_AI_GENERATED_INDICATORS: tuple[re.Pattern[str], ...] = (
    re.compile(r"# AI-generated", re.IGNORECASE),
    re.compile(r"# Generated with", re.IGNORECASE),
    re.compile(r"# AI assistant", re.IGNORECASE),
    re.compile(r"# This code is AI", re.IGNORECASE),
    re.compile(r"# This function was generated", re.IGNORECASE),
)
_FUNCTION_DEF_RE = re.compile(r"\s*def\s+(\w+)\s*\(")
_FORWARD_WINDOW = 10  # 注释后多少行内查找函数定义

# 严格模式下需要检查的核心目录 + 头部行数 + 非空阈值
_STRICT_SCAN_HEADER_LINES = 30
_STRICT_MIN_CONTENT_LEN = 100
_STRICT_CORE_PREFIX = "tools/scripts"


def has_ai_annotation(content: str) -> bool:
    """检查内容是否包含 AI 标注 (兼容旧测试: # [AI-GEN])"""
    return bool(AI_GEN_PATTERN.search(content))


def _line_has_ai_indicator(line: str) -> bool:
    """单行是否匹配任一 AI 生成指标 regex.

    V2.19 P3-17 拆分: 从 detect_ai_generated_functions (B=9) 抽出.
    """
    return any(p.search(line) for p in _AI_GENERATED_INDICATORS)


def _collect_functions_in_window(
    lines: list[str],
    start: int,
    reported_lines: set[int],
) -> list[dict[str, Any]]:
    """在注释行后续 _FORWARD_WINDOW 行内收集函数定义.

    V2.19 P3-17 拆分: 从 detect_ai_generated_functions (B=9) 抽出.
    """
    results: list[dict[str, Any]] = []
    upper = min(start + _FORWARD_WINDOW, len(lines))
    for j in range(start, upper):
        func_match = _FUNCTION_DEF_RE.match(lines[j])
        if func_match is None:
            continue
        line_no = j + 1
        if line_no in reported_lines:
            continue
        reported_lines.add(line_no)
        results.append({"function": func_match.group(1), "line": line_no})
    return results


def detect_ai_generated_functions(content: str) -> list[dict[str, Any]]:
    """检测可能由 AI 生成的函数 (orchestrator).

    V2.19 P3-17 拆分: 从 B=9 / 25 行函数拆出 2 个 helper + 提升常量.
    主函数仅负责: 遍历注释行 → 委托判定 + 窗口收集 → 去重.
    """
    lines = content.split("\n")
    reported: set[int] = set()
    results: list[dict[str, Any]] = []

    for i, line in enumerate(lines):
        # 仅检测注释行中的 AI 指标，避免命中字符串字面量
        if not line.lstrip().startswith("#"):
            continue
        if not _line_has_ai_indicator(line):
            continue
        results.extend(_collect_functions_in_window(lines, i + 1, reported))

    return results


def check_file(filepath: Path) -> dict[str, Any]:
    """检查单个文件的 AI 标注"""
    try:
        content = filepath.read_text(encoding="utf-8")
    except FileNotFoundError:
        return {"passed": False, "issues": ["文件不存在"], "has_annotation": False}
    except OSError as e:
        return {"passed": False, "issues": [f"读取失败: {e}"], "has_annotation": False}

    issues = []
    has_annotation = has_ai_annotation(content)

    # 检查是否有 AI 生成标记但缺少标准标注
    has_ai_marker = False
    for pattern in [
        r"# AI-generated",
        r"# Generated with",
        r"# AI assistant",
        r"# This code is AI",
        r"# This function was generated",
    ]:
        if re.search(pattern, content, re.IGNORECASE):
            has_ai_marker = True
            break

    if has_ai_marker and not has_annotation:
        issues.append("检测到 AI 生成标记但缺少标准 # [AI-GEN] 标注")

    return {
        "passed": len(issues) == 0,
        "issues": issues,
        "has_annotation": has_annotation,
    }


def fix_file(filepath: Path, model: str = "AI") -> bool:
    """尝试自动修复文件添加标注 (兼容旧测试)"""
    try:
        content = filepath.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False

    if has_ai_annotation(content):
        return False  # 已有标注

    # 添加标注到文件开头
    new_content = f"# [AI-GEN] Generated by {model}\n{content}"
    try:
        filepath.write_text(new_content, encoding="utf-8")
        return True
    except (OSError, UnicodeEncodeError):
        return False


def _has_strict_annotation(lines: list[str]) -> bool:
    """扫描文件头部 30 行, 检查是否有 AI 标注 (任一 pattern).

    V2.19 P3-18 拆分: 从 check_strict_mode (B=9) 抽出.
    """
    for line in lines[:_STRICT_SCAN_HEADER_LINES]:
        if AI_GENERATED_PATTERN.match(line) or AI_ASSISTED_PATTERN.match(line) or AI_REVIEWED_PATTERN.match(line):
            return True
    return False


def _build_missing_annotation_issue(filepath: Path) -> dict[str, Any]:
    """构造"核心脚本缺少 AI 标注"建议项.

    V2.19 P3-18 拆分: 从 check_strict_mode (B=9) 抽出.
    """
    return {
        "file": str(filepath),
        "issue": "核心脚本建议添加 AI 标注 (# ai-generated/ai-assisted/ai-reviewed)",
        "severity": "info",
    }


def check_strict_mode(filepath: Path) -> list[dict[str, Any]]:
    """严格模式：检查所有非空 Python 文件是否有 AI 标注（可选策略）.

    V2.19 P3-18 拆分: 从 B=9 / 32 行函数拆出 2 个 helper.
    主函数仅负责: 读取文件 → 路径守卫 → 委托扫描 → 条件追加 issue.
    """
    try:
        content = filepath.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return []

    # 只检查项目核心代码（tools/scripts/ 下的文件）
    if _STRICT_CORE_PREFIX not in str(filepath):
        return []

    if _has_strict_annotation(content.split("\n")):
        return []

    # 对于核心脚本，建议有标注（但不强制，仅警告）
    if len(content.strip()) <= _STRICT_MIN_CONTENT_LEN:
        return []
    return [_build_missing_annotation_issue(filepath)]


def _collect_files(args: argparse.Namespace) -> list[Path]:
    """Collect files to check based on args."""
    if args.file:
        return [args.file]
    if args.path:
        return [f for f in Path(args.path).rglob("*") if f.is_file() and f.suffix in TARGET_EXTENSIONS]
    return [f for f in Path("tools/scripts").rglob("*.py") if "__pycache__" not in str(f)]


def _process_file(filepath: Path, args: argparse.Namespace) -> tuple[str, int]:
    """Process a single file, return (status, fix_applied)."""
    result = check_file(filepath)

    if not result["passed"]:
        for issue in result["issues"]:
            print(f"   {issue}")

    fix_applied = 0
    if args.fix and not result["has_annotation"]:
        if fix_file(filepath, args.model):
            print(f"   🔧 {filepath.name} - 已自动标注")
            fix_applied = 1

    if result["passed"]:
        if args.strict and not result["has_annotation"]:
            return ("warn", fix_applied)
        return ("pass", fix_applied)
    return ("fail", fix_applied)


def _print_summary(passed: int, warned: int, failed: int) -> None:
    """Print summary and exit."""
    print("\n" + "=" * 60)
    print(f"  结果: {passed} 通过, {warned} 警告, {failed} 失败")
    print("=" * 60)
    sys.exit(1 if failed > 0 else 0)


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="检查 AI 代码标注")
    parser.add_argument("--path", type=Path, help="检查指定目录")
    parser.add_argument("--file", type=Path, help="检查单个文件")
    parser.add_argument("--fix", action="store_true", help="自动添加标注")
    parser.add_argument("--model", default="unknown", help="AI 模型名称")
    parser.add_argument("--strict", action="store_true", help="严格模式 (警告未标注)")
    args = parser.parse_args()

    print("=" * 60)
    print("  AI 代码标注检查")
    print("=" * 60)

    files_to_check = _collect_files(args)

    passed = 0
    warned = 0
    failed = 0

    for filepath in sorted(files_to_check):
        status, _ = _process_file(filepath, args)
        if status == "pass":
            print(f"✅ {filepath.name}")
            passed += 1
        elif status == "warn":
            print(f"⚠️  {filepath.name} - 缺少 [AI-GEN] 标注")
            warned += 1
        else:
            print(f"❌ {filepath.name}")
            failed += 1

    _print_summary(passed, warned, failed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
